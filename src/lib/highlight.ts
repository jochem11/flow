// A small syntax highlighter for the code and SQL previews: splits code into
// tokens (comments, strings, numbers, keywords, types, ...) that are colored
// with the `.tok-*` classes in styles.css. Good enough for generated code; not a parser.

import type { CodeLanguage } from "./types";

export type HighlightLanguage = CodeLanguage | "sql" | "mermaid";

export type TokenKind = "comment" | "string" | "number" | "keyword" | "type" | "annotation" | "function" | "plain";
export interface Token {
  text: string;
  kind: TokenKind;
}

const words = (s: string) => new Set(s.split(/\s+/).filter(Boolean));

const KEYWORDS: Record<HighlightLanguage, Set<string>> = {
  typescript: words(`export import from class interface enum extends implements abstract public private protected
    static readonly new return throw if else for while const let var function this null undefined true false void
    number string boolean unknown any never type`),
  java: words(`package import public private protected class interface enum extends implements abstract static final
    new return throw if else for while void int long double float boolean char byte short this null true false
    super`),
  csharp: words(`using namespace public private protected internal class interface enum abstract static virtual
    override sealed new return throw if else for while void int long double float decimal bool string object
    get set this null true false`),
  python: words(`from import class def return raise if else elif for while pass None True False self and or not
    in is with as lambda`),
  kotlin: words(`package import class interface enum abstract open override private protected internal public
    fun val var return throw if else for while null true false this super object`),
  rust: words(`pub struct enum trait impl fn let mut const static use mod self Self for in return if else match
    where dyn true false as`),
  go: words(`package import type struct interface func var const return if else for range switch case default
    go defer map chan nil true false iota panic int int64 float64 string bool any error`),
  sql: words(`CREATE TABLE ALTER ADD CONSTRAINT PRIMARY FOREIGN KEY REFERENCES NOT NULL DEFAULT UNIQUE ON DELETE
    UPDATE CASCADE RESTRICT SET NO ACTION GENERATED BY AS IDENTITY AUTO_INCREMENT AUTOINCREMENT PRAGMA WITH TIME
    ZONE INTEGER INT BIGINT SMALLINT NUMERIC DECIMAL NUMBER REAL FLOAT DOUBLE PRECISION BOOLEAN BIT TINYINT CHAR
    NCHAR VARCHAR NVARCHAR VARCHAR2 TEXT CLOB BLOB BYTEA VARBINARY DATE DATETIME DATETIME2 DATETIMEOFFSET
    TIMESTAMP TIMESTAMPTZ UUID UNIQUEIDENTIFIER JSON JSONB RAW MAX BINARY_DOUBLE TRUE FALSE CURRENT_TIMESTAMP
    CURRENT_DATE CURRENT_TIME SYSDATETIME`),
  mermaid: words(`flowchart graph TD LR classDiagram sequenceDiagram erDiagram class participant actor as
    activate deactivate note loop alt opt else end PK FK UK`),
};

/** How a line comment starts, per language */
const LINE_COMMENT: Record<HighlightLanguage, string> = {
  typescript: "//",
  java: "//",
  csharp: "//",
  kotlin: "//",
  rust: "//",
  go: "//",
  python: "#",
  sql: "--",
  mermaid: "%%",
};

export function highlight(code: string, lang: HighlightLanguage): Token[] {
  const keywords = KEYWORDS[lang];
  const lineComment = LINE_COMMENT[lang];
  const caseless = lang === "sql";
  const out: Token[] = [];
  const push = (text: string, kind: TokenKind) => {
    const last = out[out.length - 1];
    if (last && last.kind === kind) last.text += text;
    else out.push({ text, kind });
  };

  let i = 0;
  while (i < code.length) {
    const rest = code.slice(i);
    // Comments: to the end of the line, or /* ... */
    if (rest.startsWith(lineComment) || (lang !== "python" && rest.startsWith("/*"))) {
      const end = rest.startsWith("/*") ? rest.indexOf("*/") + 2 || rest.length : rest.indexOf("\n");
      const len = end <= 0 ? rest.length : end;
      push(rest.slice(0, len), "comment");
      i += len;
      continue;
    }
    // Strings (SQL double quotes and backticks are identifiers, not strings; in
    // Mermaid only double quotes make a string, an apostrophe is just text)
    const quote = rest[0];
    if ((quote === "'" && lang !== "mermaid") || (quote === '"' && lang !== "sql")) {
      let j = 1;
      while (j < rest.length && rest[j] !== quote && rest[j] !== "\n") j += rest[j] === "\\" ? 2 : 1;
      push(rest.slice(0, j + 1), "string");
      i += j + 1;
      continue;
    }
    // Annotations and decorators: @Override, @dataclass, #[derive(...)]
    const anno = /^(@[\w.]+|#\[[^\]]*\])/.exec(rest);
    if (anno && lang !== "sql" && lang !== "mermaid" && (lang !== "python" || rest[0] === "@")) {
      push(anno[0], "annotation");
      i += anno[0].length;
      continue;
    }
    const num = /^\d+(\.\d+)?[a-zA-Z]?/.exec(rest);
    if (num) {
      push(num[0], "number");
      i += num[0].length;
      continue;
    }
    const word = /^[\p{L}_][\p{L}\p{N}_]*/u.exec(rest);
    if (word) {
      const w = word[0];
      const next = code.slice(i + w.length).trimStart()[0];
      let kind: TokenKind = "plain";
      if (keywords.has(caseless ? w.toUpperCase() : w)) kind = "keyword";
      else if (next === "(" && lang !== "sql") kind = "function";
      else if (/^[A-Z]/.test(w) && lang !== "sql") kind = "type";
      push(w, kind);
      i += w.length;
      continue;
    }
    push(rest[0], "plain");
    i += 1;
  }
  return out;
}
