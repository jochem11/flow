use specta_typescript::semantic;
use tauri_specta::{Builder, collect_commands};

/// Return type of every command (and of the helpers they use).
/// The frontend receives an `Err(String)` as an error message.
pub type CmdResult<T> = Result<T, String>;

/// Every command the frontend may call. Both the `invoke_handler` and
/// `bindings.ts` are generated from this list, so they can never drift apart.
fn specta_builder() -> Builder<tauri::Wry> {
    use commands::{code_import, codegen, documents, eer, flow, folders, mermaid, projects, sql_import};

    Builder::<tauri::Wry>::new()
        .commands(collect_commands![
            projects::list_projects,
            projects::create_project,
            projects::update_project,
            projects::delete_project,
            folders::create_folder,
            folders::rename_folder,
            folders::move_folder,
            folders::delete_folder,
            documents::list_documents,
            documents::load_document,
            documents::create_document,
            documents::save_document,
            documents::rename_document,
            documents::move_document,
            documents::delete_document,
            flow::auto_layout,
            flow::export_document,
            eer::eer_sql,
            codegen::class_code,
            mermaid::mermaid_preview,
            sql_import::import_sql,
            code_import::import_code,
        ])
        // One TS type per struct instead of separate `X_Serialize` / `X_Deserialize` types.
        .disable_serde_phases()
        // By default f64 becomes `number | null`, because serde_json writes NaN/Infinity
        // as null. We never send NaN, so plain `number` is correct.
        .semantic_types(semantic::Configuration::empty().enable_lossless_floats())
}

/// Writes the TypeScript bindings to `src/bindings.ts`.
fn export_bindings(builder: &Builder<tauri::Wry>) {
    builder
        .export(
            specta_typescript::Typescript::default().header(
                "// @ts-nocheck\n// Generated by tauri-specta. Do not edit by hand; change the Rust code instead.",
            ),
            concat!(env!("CARGO_MANIFEST_DIR"), "/../src/bindings.ts"),
        )
        .expect("failed to write src/bindings.ts");
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    let builder = specta_builder();

    // Dev builds only: every `npm run tauri dev` refreshes the generated types.
    #[cfg(debug_assertions)]
    export_bindings(&builder);

    tauri::Builder::default()
        .plugin(tauri_plugin_opener::init())
        .invoke_handler(builder.invoke_handler())
        .run(tauri::generate_context!())
        .expect("error while running tauri application");
}

#[cfg(test)]
mod tests {
    /// `cargo test` (and `npm run bindings`) regenerates the bindings without starting the app.
    #[test]
    fn export_bindings() {
        super::export_bindings(&super::specta_builder());
    }
}
