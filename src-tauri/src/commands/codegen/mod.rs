//! Code from the UML classes in a flowchart: TypeScript, Java, C#, Python, Kotlin, Rust, Go.
//!
//! A class node's text is its name (with an optional «interface», «abstract» or
//! «enum» line above it), then a `--` line, its attributes, another `--`, and its
//! operations. Rows use UML notation; the editor checks them with the same rules
//! (`src/lib/umlClass.ts`):
//!
//!   attribute   [+|-|#|~] name: Type [= default]
//!   operation   [+|-|#|~] name(param: Type, ...)[: ReturnType]
//!
//! `static` (or `{static}`) and `{abstract}` may be added. Types are written like
//! `int`, `string`, `Money`, `List<Line>`, `Line[]` and `Customer?` (optional).
//!
//! Getters and setters get a real body: an operation that returns one of the
//! class's attributes (`getName(): name`, or `getName()` / `isPaid()` for an
//! attribute `name` / `paid`) returns it, and `setName(value: T)` sets it.
//! Everything else throws "not implemented".
//!
//! Lines between classes, in UML notation:
//!   hollow triangle at the end   extends (dashed: implements)
//!   diamond at the start         the start class has the end class (composition / aggregation)
//!   arrow at the end             association: the start class has the end class
//! A multiplicity with `*` (or an upper bound above 1) at the end makes it a list.

