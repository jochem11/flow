pub fn generate(flow: &FlowDoc, lang: CodeLanguage, title: &str) -> Vec<CodeFile> {
    let classes = read_classes(flow);
    let base = snake(title);
    let base = if base.is_empty() { "model".to_string() } else { base };
    let header = |c: &str| format!("{c} Generated by Flow from the class diagram \"{title}\"\n");
    match lang {
        CodeLanguage::TypeScript => vec![CodeFile { name: format!("{base}.ts"), content: header("//") + "\n" + &typescript(&classes) }],
        CodeLanguage::Python => vec![CodeFile { name: format!("{base}.py"), content: header("#") + &python(&classes) }],
        CodeLanguage::CSharp => vec![CodeFile { name: format!("{}.cs", pascal(&base)), content: header("//") + &csharp(&classes) }],
        CodeLanguage::Kotlin => vec![CodeFile { name: format!("{}.kt", pascal(&base)), content: header("//") + &kotlin(&classes) }],
        CodeLanguage::Rust => vec![CodeFile { name: format!("{base}.rs"), content: header("//") + "\n" + &rust(&classes) }],
        CodeLanguage::Go => vec![CodeFile { name: format!("{base}.go"), content: header("//") + "\n" + &go(&classes) }],
        // One public type per file
        CodeLanguage::Java => classes
            .iter()
            .map(|c| CodeFile { name: format!("{}.java", c.name), content: header("//") + &java(c, &classes) })
            .collect(),
    }
}

