//! SQL into an EER diagram: reads `CREATE TABLE` and `ALTER TABLE … ADD` from a
//! script of any of the databases the SQL export writes (PostgreSQL, MySQL,
//! SQLite, SQL Server, Oracle), and from most other scripts too.
//!
//! The script is split into statements here (so comments above a table become its
//! comment, and one statement that cannot be read does not stop the rest); each is
//! parsed with `sqlparser`, trying the dialects in turn.

use std::collections::{HashMap, HashSet};

use sqlparser::ast::{
    AlterColumnOperation, AlterTableOperation, ColumnDef, ColumnOption, CommentObject, CreateTable, Expr, ForeignKeyConstraint, ObjectName, ReferentialAction,
    Statement, TableConstraint,
};
use sqlparser::dialect::{
    Dialect, GenericDialect, MsSqlDialect, MySqlDialect, OracleDialect, PostgreSqlDialect, SQLiteDialect,
};
use sqlparser::parser::Parser;

use crate::models::{Attribute, Cardinality, ColumnPair, DataType, Entity, RefAction, Relation, SqlImport};

/// The tables and relations in a SQL script, to add to an EER diagram.
#[tauri::command]
#[specta::specta]
pub fn import_sql(sql: String) -> SqlImport {
    read_sql(&sql)
}

pub fn read_sql(sql: &str) -> SqlImport {
    let mut r = Reader::default();
    for (comment, stmt) in statements(sql) {
        let words: Vec<String> = stmt.split_whitespace().take(2).map(str::to_uppercase).collect();
        // Only tables are drawn: sequences, grants, settings, data, ... may be anything
        let table = words.len() == 2 && matches!(words[0].as_str(), "CREATE" | "ALTER" | "COMMENT") && words[1] == "TABLE"
            || words.first().is_some_and(|w| w == "COMMENT");
        match parse(&stmt) {
            Some(parsed) => {
                for s in parsed {
                    r.statement(s, comment.clone());
                }
            }
            None if table => r.skipped.push(format!("Could not read: {}", short(&stmt))),
            None => {}
        }
    }
    r.finish()
}

fn parse(stmt: &str) -> Option<Vec<Statement>> {
    let dialects: [&dyn Dialect; 6] =
        [&GenericDialect {}, &PostgreSqlDialect {}, &MySqlDialect {}, &MsSqlDialect {}, &SQLiteDialect {}, &OracleDialect {}];
    dialects.iter().find_map(|d| Parser::parse_sql(*d, stmt).ok())
}

/// The first line of a statement, for a message.
fn short(stmt: &str) -> String {
    let line = stmt.lines().next().unwrap_or("").trim();
    if line.chars().count() > 80 { format!("{}…", line.chars().take(80).collect::<String>()) } else { line.to_string() }
}

/// The statements in a script, each with the `--` comment lines right above it.
/// Splits on `;` outside strings, quoted names and comments.
fn statements(sql: &str) -> Vec<(Option<String>, String)> {
    let chars: Vec<char> = sql.chars().collect();
    let mut out = vec![];
    let mut cur = String::new();
    let mut comments: Vec<String> = vec![];
    let mut push = |cur: &mut String, comments: &mut Vec<String>| {
        if !cur.trim().is_empty() {
            // Not the header of the export, nor the "Name: x; Type: TABLE; ..." of pg_dump
            let kept: Vec<&str> = comments
                .iter()
                .map(String::as_str)
                .filter(|c| !c.is_empty() && !c.starts_with("Generated by Flow") && !(c.starts_with("Name: ") && c.contains("; Type: ")))
                .collect();
            out.push(((!kept.is_empty()).then(|| kept.join("\n")), cur.trim().to_string()));
        }
        cur.clear();
        comments.clear();
    };
    let mut i = 0;
    while i < chars.len() {
        let c = chars[i];
        let next = chars.get(i + 1).copied();
        // A psql command (\connect, \restrict): one line, without a `;`
        if c == '\\' && chars[..i].iter().rev().take_while(|&&x| x != '\n').all(|x| x.is_whitespace()) {
            i = chars[i..].iter().position(|&x| x == '\n').map_or(chars.len(), |p| i + p);
        } else if c == '-' && next == Some('-') {
            let end = chars[i..].iter().position(|&x| x == '\n').map_or(chars.len(), |p| i + p);
            // Above a statement: its comment. Inside one: just left out.
            if cur.trim().is_empty() {
                comments.push(chars[i + 2..end].iter().collect::<String>().trim().to_string());
            }
            i = end;
        } else if c == '/' && next == Some('*') {
            i = (i + 2..chars.len().saturating_sub(1)).find(|&j| chars[j] == '*' && chars[j + 1] == '/').map_or(chars.len(), |j| j + 2);
            cur.push(' ');
        } else if matches!(c, '\'' | '"' | '`' | '[') {
            let close = if c == '[' { ']' } else { c };
            let end = (i + 1..chars.len()).find(|&j| chars[j] == close).unwrap_or(chars.len() - 1);
            cur.extend(&chars[i..=end]);
            i = end + 1;
        } else if c == ';' {
            push(&mut cur, &mut comments);
            i += 1;
        } else {
            cur.push(c);
            i += 1;
        }
    }
    push(&mut cur, &mut comments);
    out
}

/// A foreign key as written, by names; turned into a relation at the end.
struct Fk {
    table: String,
    columns: Vec<String>,
    target: String,
    target_columns: Vec<String>,
    on_delete: RefAction,
    on_update: RefAction,
}

#[derive(Default)]
struct Reader {
    entities: Vec<Entity>,
    fks: Vec<Fk>,
    skipped: Vec<String>,
}

fn uid() -> String {
    uuid::Uuid::new_v4().to_string()
}

/// The table name without schema or quotes: `"public"."order"` → `order`.
fn table_name(n: &ObjectName) -> String {
    n.0.last().and_then(|p| p.as_ident()).map_or_else(|| n.to_string(), |i| i.value.clone())
}

/// A column named in a constraint.
fn column_name(e: &Expr) -> String {
    match e {
        Expr::Identifier(i) => i.value.clone(),
        other => other.to_string().trim_matches(|c| matches!(c, '"' | '`' | '[' | ']')).to_string(),
    }
}

fn action(a: Option<ReferentialAction>) -> RefAction {
    match a {
        Some(ReferentialAction::Cascade) => RefAction::Cascade,
        Some(ReferentialAction::Restrict) => RefAction::Restrict,
        Some(ReferentialAction::SetNull) => RefAction::SetNull,
        Some(ReferentialAction::SetDefault) => RefAction::SetDefault,
        Some(ReferentialAction::NoAction) | None => RefAction::NoAction,
    }
}

impl Reader {
    fn find(&self, name: &str) -> Option<usize> {
        self.entities.iter().position(|e| e.name.eq_ignore_ascii_case(name))
    }

    fn statement(&mut self, s: Statement, comment: Option<String>) {
        match s {
            Statement::CreateTable(t) => self.create_table(t, comment),
            Statement::AlterTable(a) => {
                let name = table_name(&a.name);
                let Some(i) = self.find(&name) else {
                    self.skipped.push(format!("ALTER TABLE {name}: there is no CREATE TABLE for it"));
                    return;
                };
                for op in a.operations {
                    match op {
                        AlterTableOperation::AddConstraint { constraint, .. } => self.constraint(i, &constraint),
                        AlterTableOperation::AddColumn { column_def, .. } => {
                            let a = self.column(&name, &column_def);
                            self.entities[i].attributes.push(a);
                        }
                        // How pg_dump writes a serial column
                        AlterTableOperation::AlterColumn { column_name, op: AlterColumnOperation::SetDefault { value } } => {
                            let e = &mut self.entities[i];
                            if let Some(a) = e.attributes.iter_mut().find(|a| a.name.eq_ignore_ascii_case(&column_name.value)) {
                                set_default(a, &value);
                            }
                        }
                        _ => {}
                    }
                }
            }
            Statement::Comment { object_type: CommentObject::Table, object_name, comment, .. } => {
                if let Some(i) = self.find(&table_name(&object_name)) {
                    self.entities[i].comment = comment.filter(|c| !c.trim().is_empty());
                }
            }
            // Indexes, views, data, ...: nothing to draw
            _ => {}
        }
    }

    fn create_table(&mut self, t: CreateTable, comment: Option<String>) {
        let name = table_name(&t.name);
        if self.find(&name).is_some() {
            self.skipped.push(format!("Table {name} is created twice; only the first is used"));
            return;
        }
        let attributes = t.columns.iter().map(|c| self.column(&name, c)).collect();
        self.entities.push(Entity { id: uid(), name, x: 0.0, y: 0.0, attributes, color: None, comment });
        let i = self.entities.len() - 1;
        for c in &t.constraints {
            self.constraint(i, c);
        }
    }

    fn column(&mut self, table: &str, c: &ColumnDef) -> Attribute {
        let written = c.data_type.to_string();
        let (data_type, length, scale, serial) = map_type(&written).unwrap_or_else(|| {
            self.skipped.push(format!("{table}.{}: type {written} is imported as text", c.name.value));
            (DataType::Text, None, None, false)
        });
        let mut a = Attribute {
            id: uid(),
            name: c.name.value.clone(),
            data_type,
            length,
            scale,
            primary_key: false,
            nullable: true,
            unique: false,
            auto_increment: serial,
            default_value: None,
        };
        for o in &c.options {
            match &o.option {
                ColumnOption::Null => a.nullable = true,
                ColumnOption::NotNull => a.nullable = false,
                ColumnOption::Default(e) => set_default(&mut a, e),
                ColumnOption::PrimaryKey(_) => {
                    a.primary_key = true;
                    a.nullable = false;
                }
                ColumnOption::Unique(_) => a.unique = true,
                ColumnOption::ForeignKey(fk) => self.fks.push(foreign_key(table, vec![a.name.clone()], fk)),
                // GENERATED … AS IDENTITY (a computed column has an expression)
                ColumnOption::Generated { generation_expr: None, .. } | ColumnOption::Identity(_) => a.auto_increment = true,
                // MySQL AUTO_INCREMENT, SQLite AUTOINCREMENT
                ColumnOption::DialectSpecific(tokens) if tokens.iter().any(|t| t.to_string().to_uppercase().contains("INCREMENT")) => {
                    a.auto_increment = true
                }
                _ => {}
            }
        }
        a
    }

    fn constraint(&mut self, i: usize, c: &TableConstraint) {
        let table = self.entities[i].name.clone();
        match c {
            TableConstraint::PrimaryKey(pk) => {
                for col in &pk.columns {
                    let name = column_name(&col.column.expr);
                    match self.entities[i].attributes.iter_mut().find(|a| a.name.eq_ignore_ascii_case(&name)) {
                        Some(a) => {
                            a.primary_key = true;
                            a.nullable = false;
                        }
                        None => self.skipped.push(format!("{table}: primary key on unknown column {name}")),
                    }
                }
            }
            TableConstraint::Unique(u) => {
                if let [col] = u.columns.as_slice() {
                    let name = column_name(&col.column.expr);
                    if let Some(a) = self.entities[i].attributes.iter_mut().find(|a| a.name.eq_ignore_ascii_case(&name)) {
                        a.unique = true;
                    }
                } else {
                    let names: Vec<String> = u.columns.iter().map(|c| column_name(&c.column.expr)).collect();
                    self.skipped.push(format!("{table}: UNIQUE over several columns ({}) is not in the diagram", names.join(", ")));
                }
            }
            TableConstraint::ForeignKey(fk) => {
                let cols = fk.columns.iter().map(|c| c.value.clone()).collect();
                self.fks.push(foreign_key(&table, cols, fk));
            }
            _ => {}
        }
    }

    fn finish(mut self) -> SqlImport {
        let mut relations = self.junctions();
        for fk in std::mem::take(&mut self.fks) {
            if let Some(r) = self.relation(&fk) {
                relations.push(r);
            }
        }
        layout(&mut self.entities, &relations);
        SqlImport { entities: self.entities, relations, skipped: self.skipped }
    }

    /// A table with only two foreign keys that together are its primary key is the
    /// table in between a many-to-many relation: it becomes that relation.
    fn junctions(&mut self) -> Vec<Relation> {
        let mut out = vec![];
        let mut gone = HashSet::new();
        for (j, e) in self.entities.iter().enumerate() {
            let fks: Vec<&Fk> = self.fks.iter().filter(|f| f.table.eq_ignore_ascii_case(&e.name)).collect();
            let referenced = self.fks.iter().any(|f| f.target.eq_ignore_ascii_case(&e.name));
            let [a, b] = fks.as_slice() else { continue };
            let (Some(ta), Some(tb)) = (self.find(&a.target), self.find(&b.target)) else { continue };
            let covered: HashSet<String> = a.columns.iter().chain(&b.columns).map(|c| c.to_lowercase()).collect();
            let only_keys = !e.attributes.is_empty()
                && e.attributes.iter().all(|x| x.primary_key && covered.contains(&x.name.to_lowercase()));
            if ta == tb || ta == j || tb == j || referenced || !only_keys {
                continue;
            }
            let (na, nb) = (&self.entities[ta].name, &self.entities[tb].name);
            out.push(Relation {
                id: uid(),
                from: self.entities[ta].id.clone(),
                to: self.entities[tb].id.clone(),
                from_cardinality: Cardinality::Many,
                to_cardinality: Cardinality::Many,
                // The name the export would give it anyway needs no label
                label: (!e.name.eq_ignore_ascii_case(&format!("{na}_{nb}"))).then(|| e.name.clone()),
                columns: vec![],
                on_delete: RefAction::NoAction,
                on_update: RefAction::NoAction,
            });
            gone.insert(e.name.to_lowercase());
        }
        self.entities.retain(|e| !gone.contains(&e.name.to_lowercase()));
        self.fks.retain(|f| !gone.contains(&f.table.to_lowercase()));
        out
    }

    fn relation(&mut self, fk: &Fk) -> Option<Relation> {
        let (Some(fi), Some(ti)) = (self.find(&fk.table), self.find(&fk.target)) else {
            self.skipped.push(format!("{}: foreign key to unknown table {}", fk.table, fk.target));
            return None;
        };
        let (from, to) = (&self.entities[fi], &self.entities[ti]);
        // Without columns, it refers to the primary key
        let target_cols: Vec<String> = if fk.target_columns.is_empty() {
            to.attributes.iter().filter(|a| a.primary_key).map(|a| a.name.clone()).collect()
        } else {
            fk.target_columns.clone()
        };
        let attr = |e: &Entity, n: &str| e.attributes.iter().find(|a| a.name.eq_ignore_ascii_case(n)).cloned();
        let pairs: Option<Vec<(Attribute, Attribute)>> = (fk.columns.len() == target_cols.len())
            .then(|| fk.columns.iter().zip(&target_cols).map(|(a, b)| Some((attr(from, a)?, attr(to, b)?))).collect::<Option<_>>())
            .flatten();
        let Some(pairs) = pairs.filter(|p| !p.is_empty()) else {
            self.skipped.push(format!("{} → {}: the foreign key columns do not match", fk.table, fk.target));
            return None;
        };
        // One-to-one when the key may appear once: UNIQUE, or the whole primary key
        let pk: HashSet<&str> = from.attributes.iter().filter(|a| a.primary_key).map(|a| a.id.as_str()).collect();
        let fk_ids: HashSet<&str> = pairs.iter().map(|(a, _)| a.id.as_str()).collect();
        let once = (pairs.len() == 1 && pairs[0].0.unique) || (!pk.is_empty() && pk == fk_ids);
        Some(Relation {
            id: uid(),
            from: from.id.clone(),
            to: to.id.clone(),
            from_cardinality: if once { Cardinality::ZeroOrOne } else { Cardinality::Many },
            to_cardinality: if pairs.iter().any(|(a, _)| a.nullable) { Cardinality::ZeroOrOne } else { Cardinality::One },
            label: None,
            columns: pairs.iter().map(|(a, b)| ColumnPair { from: a.id.clone(), to: b.id.clone() }).collect(),
            on_delete: fk.on_delete,
            on_update: fk.on_update,
        })
    }
}

fn foreign_key(table: &str, columns: Vec<String>, fk: &ForeignKeyConstraint) -> Fk {
    Fk {
        table: table.to_string(),
        columns,
        target: table_name(&fk.foreign_table),
        target_columns: fk.referred_columns.iter().map(|c| c.value.clone()).collect(),
        on_delete: action(fk.on_delete),
        on_update: action(fk.on_update),
    }
}

/// A default, or for `nextval(...)` (a sequence, as in PostgreSQL) auto increment.
fn set_default(a: &mut Attribute, e: &Expr) {
    let text = default_text(e, a.data_type);
    if text.to_lowercase().starts_with("nextval(") {
        a.auto_increment = true;
    } else {
        a.default_value = Some(text);
    }
}

/// A default as the editor shows it: strings without quotes or casts, the
/// database's "now" as CURRENT_TIMESTAMP, 1/0 of a boolean as true/false.
fn default_text(e: &Expr, t: DataType) -> String {
    // PostgreSQL casts: 'happy'::mood, '{}'::jsonb
    let mut e = e;
    while let Expr::Cast { expr, .. } = e {
        e = expr;
    }
    let mut s = e.to_string();
    // SQL Server writes defaults in parentheses: ((0))
    while s.starts_with('(') && s.ends_with(')') {
        s = s[1..s.len() - 1].trim().to_string();
    }
    let s = s.strip_prefix('N').filter(|r| r.starts_with('\'')).map_or(s.clone(), str::to_string);
    let quoted = s.len() >= 2 && s.starts_with('\'') && s.ends_with('\'');
    let s = if quoted { s[1..s.len() - 1].replace("''", "'") } else { s };
    let upper = s.to_uppercase();
    if !quoted && matches!(upper.as_str(), "SYSDATETIME()" | "GETDATE()" | "NOW()" | "SYSTIMESTAMP" | "CURRENT_TIMESTAMP()") {
        return "CURRENT_TIMESTAMP".into();
    }
    match (t, upper.as_str()) {
        (DataType::Boolean, "1" | "TRUE") => "true".into(),
        (DataType::Boolean, "0" | "FALSE") => "false".into(),
        _ => s,
    }
}

/// A SQL type as the diagram's type, length and scale, and whether it numbers
/// itself (SERIAL). None for a type it does not know.
pub fn map_type(sql: &str) -> Option<(DataType, Option<u32>, Option<u32>, bool)> {
    use DataType as T;
    let upper = sql.to_uppercase();
    // The type without what is in parentheses, and the numbers in the first ones
    let mut base = String::new();
    let mut args = String::new();
    let (mut depth, mut groups) = (0, 0);
    for c in upper.chars() {
        match c {
            '(' => depth += 1,
            ')' => {
                depth -= 1;
                groups += 1;
            }
            _ if depth > 0 && groups == 0 => args.push(c),
            _ if depth == 0 => base.push(c),
            _ => {}
        }
    }
    let base = base.split_whitespace().filter(|w| !matches!(*w, "UNSIGNED" | "SIGNED" | "ZEROFILL")).collect::<Vec<_>>().join(" ");
    let max = args.trim() == "MAX";
    let nums: Vec<u32> = args.split(',').filter_map(|n| n.trim().parse().ok()).collect();
    let (n0, n1) = (nums.first().copied(), nums.get(1).copied());
    let serial = matches!(base.as_str(), "SERIAL" | "SERIAL2" | "SERIAL4" | "SERIAL8" | "SMALLSERIAL" | "BIGSERIAL");
    let plain = |t| Some((t, None, None, serial));
    match base.as_str() {
        "TINYINT" if n0 == Some(1) => plain(T::Boolean),
        "BIT" | "BOOLEAN" | "BOOL" => plain(T::Boolean),
        // Oracle has one number type: its precision says which
        "NUMBER" => match (n0, n1.unwrap_or(0)) {
            (Some(1), 0) => plain(T::Boolean),
            (Some(p), 0) if p <= 5 => plain(T::SmallInt),
            (Some(p), 0) if p <= 10 => plain(T::Int),
            (Some(p), 0) if p <= 19 => plain(T::BigInt),
            _ => Some((T::Decimal, n0, n1, false)),
        },
        "TINYINT" | "SMALLINT" | "INT2" | "SMALLSERIAL" | "SERIAL2" => plain(T::SmallInt),
        "INT" | "INTEGER" | "INT4" | "MEDIUMINT" | "SERIAL" | "SERIAL4" => plain(T::Int),
        "BIGINT" | "INT8" | "BIGSERIAL" | "SERIAL8" => plain(T::BigInt),
        "DECIMAL" | "NUMERIC" | "DEC" | "MONEY" | "SMALLMONEY" => Some((T::Decimal, n0, n1, false)),
        "FLOAT" | "REAL" | "DOUBLE" | "DOUBLE PRECISION" | "FLOAT4" | "FLOAT8" | "BINARY_DOUBLE" | "BINARY_FLOAT" => plain(T::Float),
        // How the export writes a UUID for MySQL
        "CHAR" | "NCHAR" | "CHARACTER" if n0 == Some(36) => plain(T::Uuid),
        "CHAR" | "NCHAR" | "CHARACTER" => Some((T::Char, n0, None, false)),
        "VARCHAR" | "NVARCHAR" | "VARCHAR2" | "NVARCHAR2" | "CHARACTER VARYING" if max => plain(T::Text),
        "VARCHAR" | "NVARCHAR" | "VARCHAR2" | "NVARCHAR2" | "CHARACTER VARYING" => Some((T::Varchar, n0, None, false)),
        "TEXT" | "CLOB" | "NCLOB" | "NTEXT" | "TINYTEXT" | "MEDIUMTEXT" | "LONGTEXT" | "STRING" => plain(T::Text),
        "DATE" => plain(T::Date),
        "TIME" | "TIME WITHOUT TIME ZONE" => plain(T::Time),
        "DATETIME" | "DATETIME2" | "SMALLDATETIME" | "TIMESTAMP" | "TIMESTAMP WITHOUT TIME ZONE" => plain(T::DateTime),
        "TIMESTAMPTZ" | "TIMESTAMP WITH TIME ZONE" | "TIMESTAMP WITH LOCAL TIME ZONE" | "DATETIMEOFFSET" => plain(T::Timestamp),
        "UUID" | "UNIQUEIDENTIFIER" => plain(T::Uuid),
        "RAW" if n0 == Some(16) => plain(T::Uuid),
        "JSON" | "JSONB" => plain(T::Json),
        "BLOB" | "BYTEA" | "VARBINARY" | "BINARY" | "TINYBLOB" | "MEDIUMBLOB" | "LONGBLOB" | "IMAGE" | "RAW" => plain(T::Blob),
        _ => None,
    }
}

// The same sizes as the EER editor (src/lib/eer.ts)
const ENTITY_W: f64 = 280.0;
const HEADER_H: f64 = 38.0;
const ROW_H: f64 = 26.0;
const BOTTOM_PAD: f64 = 6.0;

/// Tables in columns by how far they are from the tables they refer to: tables
/// without foreign keys on the left, those that refer to them to the right.
fn layout(entities: &mut [Entity], relations: &[Relation]) {
    let index: HashMap<&str, usize> = entities.iter().enumerate().map(|(i, e)| (e.id.as_str(), i)).collect();
    let mut refers: Vec<Vec<usize>> = vec![vec![]; entities.len()];
    for r in relations.iter().filter(|r| !r.columns.is_empty() && r.from != r.to) {
        if let (Some(&a), Some(&b)) = (index.get(r.from.as_str()), index.get(r.to.as_str())) {
            refers[a].push(b);
        }
    }
    fn depth(i: usize, refers: &[Vec<usize>], memo: &mut [Option<usize>], busy: &mut [bool]) -> usize {
        if let Some(d) = memo[i] {
            return d;
        }
        if busy[i] {
            return 0; // a cycle of foreign keys
        }
        busy[i] = true;
        let d = refers[i].iter().map(|&j| depth(j, refers, memo, busy) + 1).max().unwrap_or(0);
        busy[i] = false;
        memo[i] = Some(d);
        d
    }
    let mut memo = vec![None; entities.len()];
    let mut busy = vec![false; entities.len()];
    let mut bottom: HashMap<usize, f64> = HashMap::new();
    for i in 0..entities.len() {
        let d = depth(i, &refers, &mut memo, &mut busy);
        let y = bottom.entry(d).or_insert(0.0);
        entities[i].x = d as f64 * (ENTITY_W + 100.0);
        entities[i].y = *y;
        *y += HEADER_H + entities[i].attributes.len().max(1) as f64 * ROW_H + BOTTOM_PAD + 40.0;
    }
}

