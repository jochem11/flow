    /// The SQL export for every database, read back: the same tables, columns, keys and relations.
    #[test]
    fn round_trip() {
        let doc = shop();
        for d in [SqlDialect::Postgres, SqlDialect::Mysql, SqlDialect::Sqlite, SqlDialect::SqlServer, SqlDialect::Oracle] {
            let sql = to_sql(&doc, d, "Shop");
            let got = read_sql(&sql);
            assert!(got.skipped.is_empty(), "{d:?}: {:?}\n{sql}", got.skipped);
            let names: Vec<&str> = got.entities.iter().map(|e| e.name.as_str()).collect();
            assert_eq!(names, ["customer", "order", "product"], "{d:?}");
            assert_eq!(got.entities[0].comment.as_deref(), Some("People who buy"), "{d:?}");
            for (want, have) in doc.entities.iter().zip(&got.entities) {
                for (a, b) in want.attributes.iter().zip(&have.attributes) {
                    let ctx = format!("{d:?} {}.{}", want.name, a.name);
                    assert_eq!(a.name, b.name, "{ctx}");
                    assert_eq!((a.primary_key, a.nullable && !a.primary_key, a.unique, a.auto_increment), (b.primary_key, b.nullable, b.unique, b.auto_increment), "{ctx}");
                    // SQLite stores most types as TEXT or INTEGER
                    if d != SqlDialect::Sqlite {
                        assert_eq!(a.data_type, b.data_type, "{ctx}");
                        if a.length.is_some() {
                            assert_eq!((a.length, a.scale), (b.length, b.scale), "{ctx}");
                        }
                        assert_eq!(a.default_value, b.default_value, "{ctx}");
                    }
                }
                assert_eq!(want.attributes.len(), have.attributes.len(), "{d:?} {}", want.name);
            }
            let id = |name: &str| got.entities.iter().find(|e| e.name == name).unwrap().id.clone();
            let fk = got.relations.iter().find(|r| !r.columns.is_empty()).expect("order → customer");
            assert_eq!((&fk.from, &fk.to, fk.from_cardinality, fk.to_cardinality), (&id("order"), &id("customer"), Cardinality::Many, Cardinality::One), "{d:?}");
            assert_eq!(fk.on_delete, RefAction::Cascade, "{d:?}");
            // What each database keeps of ON UPDATE RESTRICT
            let update = if matches!(d, SqlDialect::Oracle | SqlDialect::SqlServer) { RefAction::NoAction } else { RefAction::Restrict };
            assert_eq!(fk.on_update, update, "{d:?}");
            let m2m = got.relations.iter().find(|r| r.columns.is_empty()).expect("order ↔ product");
            assert_eq!((&m2m.from, &m2m.to, m2m.label.as_deref()), (&id("order"), &id("product"), None), "{d:?}");
            assert!(m2m.from_cardinality.is_many() && m2m.to_cardinality.is_many());
            // Referenced tables on the left
            assert!(got.entities[0].x < got.entities[1].x, "{d:?}");
        }
    }

    #[test]
    fn other_scripts() {
        let got = read_sql(
            "CREATE TABLE users (id SERIAL PRIMARY KEY, email TEXT UNIQUE NOT NULL, created timestamptz DEFAULT now());
             CREATE TABLE profiles (user_id INT PRIMARY KEY REFERENCES users ON DELETE CASCADE, bio TEXT, shape GEOMETRY);
             CREATE INDEX ix ON users (email);
             ALTER TABLE profiles ADD COLUMN site VARCHAR(200);
             THIS IS NOT SQL, AND NOT A TABLE EITHER;
             CREATE TABLE broken (id INT,,);",
        );
        assert_eq!(got.entities.len(), 2);
        let users = &got.entities[0];
        assert!(users.attributes[0].auto_increment && users.attributes[0].primary_key);
        assert!(users.attributes[1].unique && !users.attributes[1].nullable);
        assert_eq!(users.attributes[2].default_value.as_deref(), Some("CURRENT_TIMESTAMP"));
        assert_eq!(got.entities[1].attributes.last().unwrap().name, "site");
        let r = &got.relations[0];
        assert_eq!((r.from_cardinality, r.to_cardinality, r.on_delete), (Cardinality::ZeroOrOne, Cardinality::One, RefAction::Cascade));
        assert_eq!(got.skipped.len(), 2, "{:?}", got.skipped);
        assert!(got.skipped[0].contains("GEOMETRY"));
        assert!(got.skipped[1].starts_with("Could not read: CREATE TABLE broken"));
    }

    /// `SQL_FILE=dump.sql cargo test sql_import::tests::from_file -- --ignored --nocapture`
    /// (with `OUT=import.json` also writes what the command returns)
    #[test]
    #[ignore]
    fn from_file() {
        let got = read_sql(&std::fs::read_to_string(std::env::var("SQL_FILE").unwrap()).unwrap());
        if let Ok(out) = std::env::var("OUT") {
            std::fs::write(out, serde_json::to_string(&got).unwrap()).unwrap();
        }
        for e in &got.entities {
            let cols: Vec<String> = e.attributes.iter().map(|a| {
                let mut s = format!("{} {:?}", a.name, a.data_type);
                for (on, w) in [(a.primary_key, "PK"), (!a.nullable && !a.primary_key, "NN"), (a.unique, "UQ"), (a.auto_increment, "AI")] {
                    if on { s.push_str(&format!(" {w}")); }
                }
                if let Some(d) = &a.default_value { s.push_str(&format!(" ={d}")); }
                s
            }).collect();
            println!("{} @({}, {}){}: {}", e.name, e.x, e.y, e.comment.as_deref().map_or(String::new(), |c| format!(" -- {c}")), cols.join(", "));
        }
        let name = |id: &str| got.entities.iter().find(|e| e.id == id).map_or("?", |e| e.name.as_str());
        for r in &got.relations {
            println!("{} {:?} -> {} {:?} cols={} del={:?} upd={:?} {:?}", name(&r.from), r.from_cardinality, name(&r.to), r.to_cardinality, r.columns.len(), r.on_delete, r.on_update, r.label);
        }
        for s in &got.skipped {
            println!("SKIPPED {s}");
        }
    }

    #[test]
    fn mysqldump() {
        let got = read_sql(
            "/*!40101 SET NAMES utf8mb4 */;
            DROP TABLE IF EXISTS `customer`;
            CREATE TABLE `customer` (
              `id` int unsigned NOT NULL AUTO_INCREMENT,
              `name` varchar(120) NOT NULL COMMENT 'Full name',
              `active` tinyint(1) NOT NULL DEFAULT '1',
              PRIMARY KEY (`id`),
              KEY `ix_name` (`name`)
            ) ENGINE=InnoDB AUTO_INCREMENT=5 DEFAULT CHARSET=utf8mb4;
            CREATE TABLE `order` (
              `id` int NOT NULL AUTO_INCREMENT,
              `customer_id` int unsigned DEFAULT NULL,
              PRIMARY KEY (`id`),
              CONSTRAINT `fk_order_customer` FOREIGN KEY (`customer_id`) REFERENCES `customer` (`id`) ON DELETE SET NULL
            ) ENGINE=InnoDB;
            LOCK TABLES `customer` WRITE;
            INSERT INTO `customer` VALUES (1,'Ann',1);
            UNLOCK TABLES;",
        );
        assert!(got.skipped.is_empty(), "{:?}", got.skipped);
        let c = &got.entities[0];
        assert_eq!(c.name, "customer");
        assert!(c.attributes[0].auto_increment && c.attributes[0].primary_key);
        assert_eq!((c.attributes[2].data_type, c.attributes[2].default_value.as_deref()), (DataType::Boolean, Some("true")));
        let r = &got.relations[0];
        assert_eq!((r.to_cardinality, r.on_delete), (Cardinality::ZeroOrOne, RefAction::SetNull));
        assert_eq!(got.entities[1].attributes[1].default_value.as_deref(), Some("NULL"));
    }
